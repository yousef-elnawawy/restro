// دالة مساعدة للحصول على الدليل بناءً على المسار أو العنوان
export function getGuideForRoute(pathname: string, pageTitle?: string): PageGuide | null {
  // 1. مطابقة مباشرة بالمسار
  const cleanPath = pathname.replace(/\/$/, "")
  if (PAGE_GUIDES[cleanPath]) {
    return PAGE_GUIDES[cleanPath]
  }

  // 2. مطابقة بالمسار الفرعي
  for (const [route, guide] of Object.entries(PAGE_GUIDES)) {
    if (route !== "/dashboard" && cleanPath.startsWith(route)) {
      return guide
    }
  }

  // 3. مطابقة العنوان
  if (pageTitle) {
    const found = Object.values(PAGE_GUIDES).find(
      (g) => g.title.includes(pageTitle) || pageTitle.includes(g.title)
    )
    if (found) return found
  }

  // 4. الدليل الافتراضي
  return PAGE_GUIDES["/dashboard"] || null
}
